BEGIN;

CREATE TABLE IF NOT EXISTS users (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  email TEXT UNIQUE NOT NULL,
  password TEXT,
  role TEXT NOT NULL DEFAULT 'customer',
  balance BIGINT NOT NULL DEFAULT 0 CHECK (balance >= 0),
  blocked BIGINT NOT NULL DEFAULT 0
);

CREATE TABLE IF NOT EXISTS sessions (
  hash TEXT PRIMARY KEY,
  uid BIGINT REFERENCES users(id),
  expires BIGINT NOT NULL
);

CREATE TABLE IF NOT EXISTS keys (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  uid BIGINT REFERENCES users(id),
  hash TEXT UNIQUE NOT NULL,
  name TEXT NOT NULL,
  prefix TEXT NOT NULL,
  active BIGINT NOT NULL DEFAULT 1
);

CREATE TABLE IF NOT EXISTS inventory (
  source TEXT PRIMARY KEY,
  present BIGINT NOT NULL
);

CREATE TABLE IF NOT EXISTS models (
  id TEXT PRIMARY KEY,
  source TEXT UNIQUE NOT NULL,
  name TEXT NOT NULL,
  family TEXT NOT NULL,
  description TEXT NOT NULL DEFAULT '',
  input BIGINT NOT NULL,
  output BIGINT NOT NULL,
  maxin BIGINT NOT NULL,
  maxout BIGINT NOT NULL,
  enabled BIGINT NOT NULL DEFAULT 0
);

CREATE TABLE IF NOT EXISTS requests (
  uid BIGINT REFERENCES users(id),
  id TEXT NOT NULL,
  fp TEXT NOT NULL,
  model TEXT NOT NULL,
  inputrate BIGINT NOT NULL,
  outputrate BIGINT NOT NULL,
  maxin BIGINT NOT NULL,
  maxout BIGINT NOT NULL,
  held BIGINT NOT NULL,
  state TEXT NOT NULL,
  input BIGINT,
  output BIGINT,
  charge BIGINT,
  cost BIGINT,
  costref TEXT,
  at TEXT NOT NULL DEFAULT to_char(now() AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS'),
  PRIMARY KEY (uid, id)
);

CREATE TABLE IF NOT EXISTS ledger (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  uid BIGINT REFERENCES users(id),
  delta BIGINT NOT NULL,
  kind TEXT NOT NULL,
  ref TEXT NOT NULL,
  at TEXT NOT NULL DEFAULT to_char(now() AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS'),
  UNIQUE (uid, kind, ref)
);

CREATE TABLE IF NOT EXISTS topups (
  id TEXT PRIMARY KEY,
  uid BIGINT REFERENCES users(id),
  amount BIGINT NOT NULL,
  status TEXT NOT NULL DEFAULT 'pending',
  at TEXT NOT NULL DEFAULT to_char(now() AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS')
);

CREATE TABLE IF NOT EXISTS audit (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  actor BIGINT,
  action TEXT NOT NULL,
  detail TEXT NOT NULL,
  at TEXT NOT NULL DEFAULT to_char(now() AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS')
);

CREATE TABLE IF NOT EXISTS settings (
  k TEXT PRIMARY KEY,
  v TEXT
);

CREATE TABLE IF NOT EXISTS google_ids (
  sub TEXT PRIMARY KEY,
  uid BIGINT NOT NULL UNIQUE REFERENCES users(id)
);

CREATE TABLE IF NOT EXISTS referral_codes (
  uid BIGINT PRIMARY KEY REFERENCES users(id),
  code TEXT UNIQUE NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS referral_agents (
  uid BIGINT PRIMARY KEY REFERENCES users(id),
  rate_bps INTEGER NOT NULL CHECK (rate_bps BETWEEN 0 AND 10000),
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS usage_daily_model (
  uid BIGINT NOT NULL REFERENCES users(id),
  day DATE NOT NULL,
  model TEXT NOT NULL,
  requests BIGINT NOT NULL DEFAULT 0,
  input_tokens BIGINT NOT NULL DEFAULT 0,
  output_tokens BIGINT NOT NULL DEFAULT 0,
  cost BIGINT NOT NULL DEFAULT 0,
  PRIMARY KEY (uid, day, model)
);

COMMIT;
